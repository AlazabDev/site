/**
 * Setup Portfolio Filtering with dynamic CSS class toggle
 */
function initPortfolioFilters() {
  const filterList = document.querySelector('.portfolio-filters');
  if (!filterList) return;
  
  const filterItems = filterList.querySelectorAll('li');
  const projectItems = document.querySelectorAll('.projects-grid .project-item');
  
  filterItems.forEach(item => {
    item.addEventListener('click', function(e) {
      e.preventDefault();
      
      // Remove active class from all filters
      filterItems.forEach(i => i.classList.remove('filter-active'));
      // Add active class to clicked filter
      this.classList.add('filter-active');
      
      const filterValue = this.getAttribute('data-filter');
      
      projectItems.forEach(project => {
        if (filterValue === '*' || project.classList.contains(filterValue.substring(1))) {
          project.classList.remove('hide');
          project.classList.add('show');
        } else {
          project.classList.remove('show');
          project.classList.add('hide');
        }
      });
      
      // Refresh AOS to adjust animate timings on filter change
      if (typeof AOS !== 'undefined') {
        AOS.refresh();
      }
    });
  });
}
